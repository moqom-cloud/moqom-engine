//! The observability surface: metrics, health, and who is connected.
//!
//! # Why this is a second listener and not part of the relay port
//!
//! The relay port speaks QUIC to the internet. This speaks HTTP to a scraper on
//! a private network, and the two have opposite exposure requirements: one must
//! be reachable by anyone, the other must be reachable by almost nobody. Sharing
//! a port would mean the only thing standing between a stranger and a list of
//! connected participants is a path prefix.
//!
//! It is off unless `MOQOM_RELAY_ADMIN_ADDR` is set. A metrics endpoint that
//! appears by default is one that gets exposed by accident.
//!
//! # Why there is no HTTP library here
//!
//! This serves four fixed paths, answers only GET, reads no bodies, and does not
//! keep connections alive. That is about sixty lines against `TcpListener`, or a
//! dependency tree with its own release cadence and its own advisories, in a
//! workspace that vendors its QUIC stack specifically to control that surface.
//! The bounds that make it safe are explicit below: a request that exceeds
//! [`MAX_REQUEST`] or takes longer than [`REQUEST_TIMEOUT`] is dropped
//! unanswered.
//!
//! # Why the JSON is generated by hand
//!
//! Same reasoning, plus one thing specific to this data: namespace fields are
//! arbitrary bytes, because the specification imposes no character encoding. A
//! derive-based serializer would need a wrapper type per field to say what to do
//! with bytes that are not UTF-8. Doing it explicitly means the answer is
//! visible — see [`json_string`], which is where the escaping that keeps this
//! output parseable actually lives.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io;
use std::net::SocketAddr;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use moqom_proto::model::{Kind, Scope, TrackNamespace};
