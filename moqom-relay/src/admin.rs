//! The observability surface: metrics, health, and who is connected.
//!
//! # Why this is a second listener and not part of the relay port
//!
//! The relay port speaks QUIC to the internet. This speaks HTTP to a scraper on
//! a private network, and the two have opposite exposure requirements: one must
//! be reachable by anyone, the other must be reachable by almost nobody. Sharing
//! a port would mean the only thing standing between a stranger and a list of
//! connected participants is a path prefix.
//!
//! It is off unless `MOQOM_RELAY_ADMIN_ADDR` is set. A metrics endpoint that
//! appears by default is one that gets exposed by accident.
//!
//! Every path but the two probes needs a credential unless the listener is on
//! loopback, and an unauthenticated listener refuses to bind anywhere else. See
//! [`crate::admin_auth`].
//!
//! # Why there is no HTTP library here
//!
//! This serves four fixed paths, answers only GET, reads no bodies, and does not
//! keep connections alive. That is about sixty lines against `TcpListener`, or a
//! dependency tree with its own release cadence and its own advisories, in a
//! workspace that vendors its QUIC stack specifically to control that surface.
//! The bounds that make it safe are explicit below: a request that exceeds
//! `MAX_REQUEST` or takes longer than `REQUEST_TIMEOUT` is dropped unanswered.
//!
//! # Why the JSON is generated by hand
//!
//! Same reasoning, plus one thing specific to this data: namespace fields are
//! arbitrary bytes, because the specification imposes no character encoding. A
//! derive-based serializer would need a wrapper type per field to say what to do
//! with bytes that are not UTF-8. Doing it explicitly means the answer is
//! visible — see `json_string`, which is where the escaping that keeps this
//! output parseable actually lives.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io;
use std::net::SocketAddr;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use moqom_proto::model::{Kind, Scope, TrackNamespace};
use tokio::io::{AsyncRead, AsyncReadExt as _, AsyncWrite, AsyncWriteExt as _};
use tokio::net::TcpListener;

use crate::admin_auth::{Guard, Verdict};
use crate::fabric::Fabric;
use crate::metrics::{Gauges, Metrics};

/// Largest request this will read before giving up.
///
/// A scrape is a request line and a few headers. Anything approaching this is
/// either broken or probing.
const MAX_REQUEST: usize = 8 * 1024;

/// How long a client has to send a complete request.
const REQUEST_TIMEOUT: Duration = Duration::from_secs(10);

/// An HTTP response, as a status and a body.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Response {
    /// The status code.
    pub status: u16,
    /// The `Content-Type` header value.
    pub content_type: &'static str,
    /// The body.
    pub body: String,
}

impl Response {
    fn text(status: u16, body: impl Into<String>) -> Self {
        Self {
            status,
            content_type: "text/plain; charset=utf-8",
            body: body.into(),
        }
    }

    fn json(body: String) -> Self {
        Self {
            status: 200,
            content_type: "application/json",
            body,
        }
    }

    fn metrics(body: String) -> Self {
        Self {
            status: 200,
            // The version parameter is what tells a scraper this is the text
            // exposition format rather than something it should sniff.
            content_type: "text/plain; version=0.0.4; charset=utf-8",
            body,
        }
    }

    fn reason(&self) -> &'static str {
        match self.status {
            200 => "OK",
            400 => "Bad Request",
            401 => "Unauthorized",
            403 => "Forbidden",
            404 => "Not Found",
            405 => "Method Not Allowed",
            503 => "Service Unavailable",
            _ => "Internal Server Error",
        }
    }

    fn encode(&self) -> Vec<u8> {
        let mut head = String::with_capacity(128);
        let _ = write!(
            head,
            "HTTP/1.1 {} {}\r\n\
             content-type: {}\r\n\
             content-length: {}\r\n\
             cache-control: no-store\r\n\
             connection: close\r\n",
            self.status,
            self.reason(),
            self.content_type,
            self.body.len()
        );
        if self.status == 401 {
            head.push_str("www-authenticate: Bearer realm=\"moqom-relay-admin\"\r\n");
        }
        head.push_str("\r\n");
        let mut out = head.into_bytes();
        out.extend_from_slice(self.body.as_bytes());
        out
    }
}

/// What the admin endpoints read from.
///
/// Clonable so the accept loop can hand a copy to each connection.
#[derive(Debug, Clone)]
pub struct Surface {
    metrics: Metrics,
    fabric: Fabric,
    /// Cleared when the relay begins draining, so an orchestrator stops sending
    /// it new connections before it stops answering the ones it has.
    ready: Arc<AtomicBool>,
}

impl Surface {
    /// A surface over one relay's state.
    #[must_use]
    pub fn new(metrics: Metrics, fabric: Fabric) -> Self {
        Self {
            metrics,
            fabric,
            ready: Arc::new(AtomicBool::new(true)),
        }
    }

    /// Report that the relay is draining.
    ///
    /// Liveness stays up: the process is working, and killing it mid-drain is
    /// the opposite of what a drain is for. Readiness goes down, which is what
    /// takes it out of a load balancer's rotation.
    pub fn draining(&self) {
        self.ready.store(false, Ordering::Relaxed);
    }

    /// Answer one request target.
    ///
    /// Separated from the socket so the whole surface is testable without
    /// binding a port, which is also why it takes a path rather than a stream.
    #[must_use]
    pub fn respond(&self, target: &str) -> Response {
        // A query string is not part of routing here, but scrapers do append
        // them, and treating `/metrics?x=1` as unknown would be a confusing
        // failure to debug.
        let path = target.split(['?', '#']).next().unwrap_or(target);
        match path {
            "/metrics" => {
                let mut exposition = self.metrics.expose(&self.gauges());
                // Only beside the rest: a relay with metrics off exposes nothing.
                if self.metrics.is_enabled() {
                    exposition.push_str(&self.fabric.usage().expose());
                }
                Response::metrics(exposition)
            }
            "/healthz" => Response::text(200, "ok\n"),
            "/readyz" => {
                if self.ready.load(Ordering::Relaxed) {
                    Response::text(200, "ready\n")
                } else {
                    Response::text(503, "draining\n")
                }
            }
            "/sessions" => Response::json(self.sessions_json()),
            "/rooms" => Response::json(self.rooms_json()),
            "/tracks" => Response::json(self.tracks_json()),
            "/geo" => Response::json(self.geo_json()),
            "/" => Response::text(
                200,
                "moqom-relay\n\n/metrics\n/healthz\n/readyz\n/sessions\n/rooms\n/tracks\n/geo\n",
            ),
            _ => Response::text(404, "no such endpoint\n"),
        }
    }

    /// The values the exposition needs that are held elsewhere.
    fn gauges(&self) -> Gauges {
        let announcements = self.fabric.announcements();
        let occupancy = Occupancy::of(announcements.iter().map(|(namespace, _)| namespace));
        let cache = self.fabric.cache().stats();
        let (hits, misses) = self.fabric.cache().hit_rate();

        // `None` means the kernel could not be asked at all, which is off
        // Linux. Reported the same way as an undisciplined clock, because for
        // anything downstream it means the same thing: do not trust the
        // timestamps this relay writes.
        let clock = self.fabric.clock().health().unwrap_or_default();

        Gauges {
            namespaces: announcements.len(),
            rooms: occupancy.rooms.len(),
            participants: occupancy.participants,
            cache_tracks: cache.tracks,
            cache_groups: cache.groups,
            cache_objects: cache.objects,
            cache_bytes: cache.bytes,
            cache_hits: hits,
            cache_misses: misses,
            clock_synchronised: clock.synchronised,
            clock_error: clock.max_error,
            clock_leap_pending: clock.leap_pending,
            clock_fallbacks: self.fabric.clock().fallbacks(),
        }
    }

    /// Every connected session, with its transport state.
    ///
    /// This is the endpoint with unbounded cardinality, which is exactly why it
    /// is an endpoint and not a metric: it costs nothing until asked for, and
    /// what it returns is a snapshot rather than a time series per participant.
    fn sessions_json(&self) -> String {
        let announcements = self.fabric.announcements();
        let mut out = String::from("{\"sessions\":[");

        for (index, (id, live)) in self.metrics.sessions().into_iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let published: Vec<&TrackNamespace> = announcements
                .iter()
                .filter(|(_, owner)| *owner == id)
                .map(|(namespace, _)| namespace)
                .collect();

            // Milliseconds with one decimal: a diagnostic endpoint is read by a
            // human, and microsecond precision on an estimate this noisy would
            // be false confidence.
            #[allow(clippy::cast_precision_loss)] // display precision only
            let rtt_ms = live.rtt_micros.load(Ordering::Relaxed) as f64 / 1000.0;

            let _ = write!(
                out,
                "{{\"id\":{},\"peer\":{},\"carrier\":\"{}\",\"age_seconds\":{},\
                 \"rtt_ms\":{:.1},\"cwnd_bytes\":{},\"lost_packets\":{},\"mtu\":{},\
                 \"udp_tx_bytes\":{},\"udp_rx_bytes\":{},\"forwarding_tracks\":{},\
                 \"announced\":[",
                id.number(),
                json_string(live.peer.as_bytes()),
                carrier_name(live.carrier),
                live.since.elapsed().as_secs(),
                rtt_ms,
                live.cwnd.load(Ordering::Relaxed),
                live.lost_packets.load(Ordering::Relaxed),
                live.mtu.load(Ordering::Relaxed),
                live.udp_tx_bytes.load(Ordering::Relaxed),
                live.udp_rx_bytes.load(Ordering::Relaxed),
                live.forwarding.load(Ordering::Relaxed),
            );
            for (n, namespace) in published.iter().enumerate() {
                if n > 0 {
                    out.push(',');
                }
                out.push_str(&json_namespace(namespace));
            }
            out.push_str("]}");
        }

        let _ = write!(
            out,
            "],\"count\":{},\"uptime_seconds\":{}}}",
            self.metrics.session_count(),
            self.metrics.uptime().as_secs()
        );
        out
    }

    /// Every track being forwarded, and how long since each carried anything.
    ///
    /// The endpoint to open when a viewer says a stream froze. `/sessions` will
    /// show the publisher connected with a healthy RTT, because it is: the
    /// connection is fine and the pictures stopped. `silent_ms` is the only place
    /// the difference appears, and naming the track is the point — which is also
    /// why it cannot be a metric, since a series per track is a series per
    /// participant per rung and anybody who can connect could mint them.
    ///
    /// Sorted by descending silence, so whatever is wrong is at the top.
    fn tracks_json(&self) -> String {
        let mut flows = self.metrics.flows();
        flows.sort_by(|a, b| {
            b.silence()
                .cmp(&a.silence())
                // Ties broken by name so that a quiet relay produces stable
                // output between scrapes, which is what makes diffing two of
                // them meaningful.
                .then_with(|| a.track.to_string().cmp(&b.track.to_string()))
        });

        let mut out = String::from("{\"tracks\":[");
        for (index, flow) in flows.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let _ = write!(
                out,
                "{{\"namespace\":{},\"name\":{},\"session\":{},\"alias\":{},\
                 \"age_seconds\":{},\"silent_ms\":{},\"carried\":{},\
                 \"subgroups\":{},\"bytes\":{}}}",
                json_namespace(flow.track.namespace()),
                json_string(flow.track.name()),
                flow.session.number(),
                flow.alias.get(),
                flow.since.elapsed().as_secs(),
                flow.silence().as_millis(),
                flow.has_carried(),
                flow.subgroup_count(),
                flow.byte_count(),
            );
        }
        let _ = write!(out, "],\"count\":{}}}", flows.len());
        out
    }

    /// Sessions per tenant by coarse place, with small places withheld.
    ///
    /// The same rule a tenant's live map is held to: an operator checking that
    /// geolocation works has no more need of one person's city than a tenant
    /// does. Looked up fresh on every request; see [`crate::geo`].
    fn geo_json(&self) -> String {
        let locator = crate::geo::Locator::shared();
        let census = crate::geo::Surveyor::new().survey(&self.fabric, locator);
        let disclosure = crate::geo::Disclosure::from_env();

        let mut out = String::from("{\"tenants\":[");
        for (index, (tenant, tally)) in census.tenants.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let shown = disclosure.disclose(tally);
            let _ = write!(
                out,
                "{{\"tenant\":{},\"sessions\":{},\"publishers\":{},\"viewers\":{},\
                 \"withheld\":{},\"places\":[",
                json_string(tenant.as_bytes()),
                tally.sessions(),
                tally.publishers,
                tally.viewers,
                shown.withheld,
            );
            for (n, (place, count)) in shown.places.iter().enumerate() {
                if n > 0 {
                    out.push(',');
                }
                let _ = write!(
                    out,
                    "{{\"country\":{},\"region\":{},\"city\":{},\"lat\":{},\"lon\":{},\"sessions\":{}}}",
                    json_string(place.country.as_bytes()),
                    json_string(place.region.as_bytes()),
                    json_string(place.city.as_bytes()),
                    place.latitude,
                    place.longitude,
                    count,
                );
            }
            out.push_str("]}");
        }
        let _ = write!(
            out,
            "],\"database\":{},\"min_count\":{},\"round_to\":{}}}",
            locator.is_some(),
            disclosure.min_count(),
            disclosure.round_to(),
        );
        out
    }

    /// Every room with something publishing in it.
    fn rooms_json(&self) -> String {
        let announcements = self.fabric.announcements();
        let occupancy = Occupancy::of(announcements.iter().map(|(namespace, _)| namespace));

        let mut out = String::from("{\"rooms\":[");
        for (index, ((tenant, room), slots)) in occupancy.rooms.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            let _ = write!(
                out,
                "{{\"tenant\":{},\"room\":{},\"participants\":[",
                json_string(tenant),
                json_string(room)
            );
            for (n, slot) in slots.iter().enumerate() {
                if n > 0 {
                    out.push(',');
                }
                let _ = write!(
                    out,
                    "{{\"username\":{},\"device\":{},\"stage\":\"{}\"}}",
                    json_string(&slot.username),
                    json_string(&slot.device),
                    if slot.backstage { "backstage" } else { "stage" }
                );
            }
            let _ = write!(out, "],\"count\":{}}}", slots.len());
        }
        let _ = write!(out, "],\"count\":{}}}", occupancy.rooms.len());
        out
    }

    /// Bind `addr` and answer requests until the future is dropped.
    ///
    /// `guard` decides who may read what, and `tls`, when given, is the
    /// configuration from [`crate::admin_auth::tls_config`] that verifies the
    /// client certificates a guard requiring them depends on.
    ///
    /// # Errors
    /// [`io::Error`] if the address cannot be bound, if `guard` is open and
    /// `addr` is not loopback, or if `guard` needs TLS and none was given.
    /// Per-connection failures are logged and do not stop the loop: a broken
    /// scrape must not take the endpoint down for the next one.
    pub async fn serve(
        self,
        addr: SocketAddr,
        guard: Guard,
        tls: Option<Arc<rustls::ServerConfig>>,
    ) -> io::Result<()> {
        guard
            .permits_bind(addr)
            .map_err(|e| io::Error::new(io::ErrorKind::PermissionDenied, e))?;
        if guard.needs_tls() && tls.is_none() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "client certificates are required but the admin listener has no TLS configuration",
            ));
        }
        let acceptor = tls.map(tokio_rustls::TlsAcceptor::from);
        let guard = Arc::new(guard);

        let listener = TcpListener::bind(addr).await?;
        let bound = listener.local_addr()?;
        tracing::info!(%bound, guard = ?guard, tls = acceptor.is_some(), "admin listening");

        loop {
            let (stream, peer) = match listener.accept().await {
                Ok(accepted) => accepted,
                // A failed accept is usually a file-descriptor limit, which
                // will resolve itself as connections close. Exiting the loop
                // would lose observability for the rest of the process's life,
                // which is when it is needed most.
                Err(e) => {
                    tracing::debug!(error = %e, "admin accept failed");
                    continue;
                }
            };
            let surface = self.clone();
            let guard = Arc::clone(&guard);
            let acceptor = acceptor.clone();
            tokio::spawn(async move {
                if let Err(e) = surface.connection(stream, &guard, acceptor.as_ref()).await {
                    tracing::debug!(%peer, error = %e, "admin request failed");
                }
            });
        }
    }

    /// One accepted connection: the TLS handshake if there is one, then the
    /// request.
    async fn connection(
        &self,
        stream: tokio::net::TcpStream,
        guard: &Guard,
        acceptor: Option<&tokio_rustls::TlsAcceptor>,
    ) -> io::Result<()> {
        let Some(acceptor) = acceptor else {
            return self.answer(stream, guard, false).await;
        };
        // Inside the same timeout as the request, so a peer that opens a socket
        // and never finishes the handshake is bounded exactly like one that
        // never sends a request.
        match tokio::time::timeout(REQUEST_TIMEOUT, acceptor.accept(stream)).await {
            Ok(Ok(tls)) => {
                let certified = tls.get_ref().1.peer_certificates().is_some();
                self.answer(tls, guard, certified).await
            }
            Ok(Err(e)) => Err(e),
            Err(_) => Err(io::Error::new(
                io::ErrorKind::TimedOut,
                "handshake timed out",
            )),
        }
    }

    /// Answer one request on an accepted connection.
    ///
    /// `certified` is whether the connection carried a client certificate that
    /// the TLS handshake verified; on a plaintext listener it is always false.
    async fn answer<S>(&self, mut stream: S, guard: &Guard, certified: bool) -> io::Result<()>
    where
        S: AsyncRead + AsyncWrite + Unpin,
    {
        let request = match tokio::time::timeout(REQUEST_TIMEOUT, read_head(&mut stream)).await {
            Ok(result) => result?,
            Err(_) => return Err(io::Error::new(io::ErrorKind::TimedOut, "request timed out")),
        };

        let response = match parse_target(&request) {
            Some((method @ ("GET" | "HEAD"), target)) => {
                match guard.judge(target, authorization(&request), certified) {
                    Verdict::Allow => self.respond(target),
                    Verdict::Unauthenticated => {
                        tracing::info!(method, target, "admin request without a valid token");
                        Response::text(401, "a bearer token is required\n")
                    }
                    Verdict::Forbidden => {
                        tracing::info!(method, target, "admin request refused");
                        Response::text(
                            403,
                            "not available on this listener without a client certificate\n",
                        )
                    }
                }
            }
            Some(_) => Response::text(405, "only GET\n"),
            None => Response::text(400, "unintelligible request\n"),
        };

        stream.write_all(&response.encode()).await?;
        stream.flush().await?;
        // Over TLS this sends close_notify, without which a client cannot tell a
        // complete response from a truncated one.
        stream.shutdown().await?;
        Ok(())
    }
}

/// Read until the end of the headers, or until the bounds say stop.
async fn read_head<S: AsyncRead + Unpin>(stream: &mut S) -> io::Result<String> {
    let mut buffer = Vec::with_capacity(1024);
    let mut chunk = [0u8; 1024];
    loop {
        // Checked before reading more so a client that sends exactly
        // `MAX_REQUEST` bytes of headers and no terminator cannot loop forever.
        if buffer.len() > MAX_REQUEST {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "request head too large",
            ));
        }
        if buffer.windows(4).any(|w| w == b"\r\n\r\n") {
            break;
        }
        match stream.read(&mut chunk).await? {
            0 => break,
            n => buffer.extend_from_slice(&chunk[..n]),
        }
    }
    Ok(String::from_utf8_lossy(&buffer).into_owned())
}

/// The method and target from a request head.
fn parse_target(request: &str) -> Option<(&str, &str)> {
    let line = request.lines().next()?;
    let mut parts = line.split_whitespace();
    let method = parts.next()?;
    let target = parts.next()?;
    Some((method, target))
}

/// The `Authorization` header from a request head, if it has exactly one.
///
/// Two of them is refused rather than resolved, because which one a proxy in
/// front would have used is not knowable from here.
fn authorization(request: &str) -> Option<&str> {
    let mut found = None;
    for line in request.lines().skip(1) {
        if line.is_empty() {
            break;
        }
        let Some((name, value)) = line.split_once(':') else {
            continue;
        };
        if name.trim().eq_ignore_ascii_case("authorization") {
            if found.is_some() {
                return None;
            }
            found = Some(value.trim());
        }
    }
    found
}

const fn carrier_name(carrier: moqom_proto::control::setup::Transport) -> &'static str {
    match carrier {
        moqom_proto::control::setup::Transport::Quic => "quic",
        moqom_proto::control::setup::Transport::WebTransport => "webtransport",
    }
}

/// One participant slot seen in an announcement.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct Slot {
    username: Vec<u8>,
    device: Vec<u8>,
    backstage: bool,
}

/// Who is publishing where, derived from announced namespaces.
#[derive(Debug, Default)]
struct Occupancy {
    /// Keyed by tenant and room so the ordering is stable across scrapes, which
    /// matters for anything diffing this output.
    rooms: BTreeMap<(Vec<u8>, Vec<u8>), Vec<Slot>>,
    participants: usize,
}

impl Occupancy {
    fn of<'a>(namespaces: impl Iterator<Item = &'a TrackNamespace>) -> Self {
        let mut occupancy = Self::default();
        for namespace in namespaces {
            let Some(scope) = Scope::of(namespace) else {
                continue;
            };
            let Some((tenant, room)) = scope.room_key() else {
                // A personal channel is not in a room. Counting it as one would
                // make "rooms" mean "namespaces", which is the number next to
                // it.
                continue;
            };
            let slots = occupancy
                .rooms
                .entry((tenant.to_vec(), room.to_vec()))
                .or_default();
            if let Some(participant) = scope.participant {
                let slot = Slot {
                    username: participant.username.to_vec(),
                    device: participant.device.to_vec(),
                    backstage: scope.kind == Kind::Backstage,
                };
                // A reconnecting publisher can hold two announcements for one
                // slot at once, and reporting it twice would show a room as
                // fuller than it is.
                if !slots.contains(&slot) {
                    slots.push(slot);
                    occupancy.participants += 1;
                }
            }
        }
        for slots in occupancy.rooms.values_mut() {
            slots.sort();
        }
        occupancy
    }
}

/// A namespace as a JSON array of its fields.
fn json_namespace(namespace: &TrackNamespace) -> String {
    let mut out = String::from("[");
    for (index, field) in namespace.fields().iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        out.push_str(&json_string(field));
    }
    out.push(']');
    out
}

/// Arbitrary bytes as a quoted JSON string.
///
/// Namespace fields are bytes and the specification imposes no encoding, so this
/// has to answer two questions the type system does not. Invalid UTF-8 becomes
/// U+FFFD, because the alternative is refusing to describe a session that is
/// really there. Control characters are escaped, because a room name containing
/// a newline would otherwise produce output that parses as something else — the
/// only bug in this file that could mislead rather than merely fail.
fn json_string(bytes: &[u8]) -> String {
    let text = String::from_utf8_lossy(bytes);
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c < '\u{20}' => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

